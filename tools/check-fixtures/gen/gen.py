# Генератор образцов 0.2-0.3. Ожидаемые теги/заголовки/блоки задаются вручную
# разметкой ⟦…⟧ в тексте; скрипт только снимает разметку и считает смещения
# (UTF-16 и байты UTF-8). Разбора Markdown здесь нет.
# Запуск из корня репозитория: python3 tools/check-fixtures/gen/gen.py tests/fixtures
# (после — npx vitest run tools/check-fixtures).
import json, os, sys

OUT = sys.argv[1]
L, R = '⟦', '⟧'


def u16(s):
    return len(s.encode('utf-16-le')) // 2


def u8(s):
    return len(s.encode('utf-8'))


def unmark(src):
    """Снять ⟦⟧, вернуть (текст, [(start_idx, end_idx)]) в индексах кодовых точек."""
    out, spans, stack = [], [], []
    for ch in src:
        if ch == L:
            stack.append(len(out))
        elif ch == R:
            spans.append((stack.pop(), len(out)))
        else:
            out.append(ch)
    assert not stack
    spans.sort()
    return ''.join(out), spans


def rng(text, a, b):
    return {'from': u16(text[:a]), 'to': u16(text[:b]), 'byte_from': u8(text[:a]), 'byte_to': u8(text[:b])}


def dump(path, obj):
    os.makedirs(os.path.dirname(path), exist_ok=True)
    with open(path, 'w', encoding='utf-8', newline='\n') as f:
        f.write(json.dumps(obj, ensure_ascii=False, indent=2) + '\n')


