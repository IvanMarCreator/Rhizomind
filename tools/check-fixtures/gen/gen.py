# ---------------------------------------------------------------- ссылки с байтовыми смещениями
def link_parts(text, a, b):
    raw = text[a:b]
    embed = raw.startswith('!')
    start = a + (3 if embed else 2)
    end = b - 2
    inner = text[start:end]
    bar = inner.find('|')
    alias = None
    if bar >= 0:
        tend = bar - 1 if bar > 0 and inner[bar - 1] == '\\' else bar
        alias = (start + bar + 1, end)
        head_zone = inner[:tend]
    else:
        tend = len(inner)
        head_zone = inner
    hash_ = head_zone.find('#')
    heading = None
    if hash_ >= 0:
        heading = (start + hash_ + 1, start + tend)
        tend = hash_
    target = (start, start + tend)

    def trim(r):
        if r is None:
            return None
        a, b = r
        while a < b and text[a] in ' \t':
            a += 1
        while b > a and text[b - 1] in ' \t':
            b -= 1
        return (a, b)

    target, heading, alias = trim(target), trim(heading), trim(alias)
    p = lambda r: None if r is None else rng(text, *r)
    return {'raw': raw, 'embed': embed, **rng(text, a, b), 'target': p(target), 'heading': p(heading), 'alias': p(alias)}


