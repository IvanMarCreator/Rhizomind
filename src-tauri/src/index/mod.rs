//! Индекс хранилища (выпуск 0.2, С2-4, С2-5.2, ADR 0004): для каждой заметки
//! — размер, даты, заголовки, теги и ссылки с положениями; по ним —
//! обратные ссылки (заметка → ссылки на неё) и теги (ключ → заметки).
//!
//! Не путать со **списком заметок** (`commands::NoteList`): тот знает только
//! пути и даты создания и разрешает ссылки; индекс знает, что внутри заметок
//! (план 0.2, Т3). Ссылки индекс разрешает через [`Links`](crate::links::Links) списка заметок —
//! правила С3.4 в одном месте.
//!
//! Индекс целиком в памяти; модуль — единственный, кто знает формат файла
//! `.rhizomind/index.json` (в 0.3 его заменит SQLite без изменения
//! остального кода). Текста заметок в индексе нет (Р13).
//!
//! Интерфейс модуля:
//! - [`VaultIndex`] — индекс в памяти: [`VaultIndex::upsert`] и
//!   [`VaultIndex::remove`] по одной заметке (своя запись, пачка
//!   наблюдателя — задача 0.2-1.4), запросы [`VaultIndex::backlinks`],
//!   [`VaultIndex::tags`], [`VaultIndex::tag_notes`],
//!   [`VaultIndex::links_named`] (план переписывания `relink`), снимок
//!   [`VaultIndex::entries`] и восстановление [`VaultIndex::from_entries`]
//!   (файл индекса — задача 0.2-1.3), [`VaultIndex::revision`] — «изменилось
//!   ли что-нибудь» (запись файла, событие `index:changed`);
//! - [`read_entry`] — чтение и разбор одной заметки, **вне замка** индекса;
//! - [`rebuild`] — сборка с нуля: вызывающий запускает её в фоновом потоке,
//!   файлы читаются параллельно (не больше числа ядер), замок берётся только
//!   на вставку прочитанной пачки.
//!
//! Обратные ссылки не хранятся разрешёнными: индекс помнит «ключ имени цели →
//! заметки со ссылками», а в какую заметку ведёт ссылка, решает [`Links`](crate::links::Links) в
//! момент запроса (правила С3.4). Поэтому изменение состава заметок
//! (создание, переименование, удаление, повтор имени) не требует пересчёта
//! индекса — только изменения текста заметок.

use std::ops::Range;

use crate::commands::VaultPath;
use crate::markdown::ParsedNote;

mod build;
mod memory;
#[cfg(test)]
mod tests;

pub use build::{read_entry, rebuild};
pub use memory::VaultIndex;

/// Версия формата `index.json` (`format_version`). Не та — пересборка с нуля
/// без копии старого файла (С2-4.1, Р12).
pub const FORMAT_VERSION: u32 = 1;

/// Предел размера `index.json` при чтении, байт — собственный, вместо общих
/// 4 МБ служебных файлов (С2-4.1). Больше — пересборка.
pub const MAX_INDEX_FILE_BYTES: u64 = 256 * 1024 * 1024;

/// Запись индекса об одной заметке.
#[derive(Debug, Clone, Default, PartialEq, Eq)]
pub struct NoteEntry {
    /// Размер файла, байт (сверка при открытии).
    pub size: u64,
    /// Дата изменения, мс UTC (сверка при открытии).
    pub modified_ms: i64,
    /// Дата создания, мс UTC (отображаемое написание тега — из самой старой
    /// заметки при равенстве, решение 113).
    pub created_ms: i64,
    /// Заголовки, теги и ссылки (`markdown::parse`).
    pub parsed: ParsedNote,
}

/// Где в заметке стоит ссылка на запрошенную заметку.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct LinkSite {
    /// Номер строки, с 1.
    pub line: u32,
    /// Вся ссылка в байтах текста заметки, каким его отдаёт
    /// `Vault::read_note` (без BOM, переносы `\n`; как у редактора), на
    /// момент разбора. К сырым байтам файла положения применять нельзя:
    /// BOM и `\r\n` их сдвигают; строка для панели читается по ним из текста
    /// `read_note`.
    pub span: Range<usize>,
}

/// Заметка, ссылающаяся на запрошенную, и её ссылки по порядку.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct BacklinkSource {
    /// Ссылающаяся заметка (не сама запрошенная: ссылка на себя не
    /// считается).
    pub from: VaultPath,
    /// Ссылки на запрошенную заметку.
    pub sites: Vec<LinkSite>,
}

/// Тег хранилища: отображаемое написание, ключ и число заметок.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct TagCount {
    /// Самое частое написание, при равенстве — из самой старой заметки.
    pub display: String,
    /// Ключ тега (`markdown::tag_key`).
    pub key: String,
    /// Заметок с тегом.
    pub notes: u32,
}
